def apply_all(db: sqlite3.Connection) -> None:
    for path in sorted(MIGRATION_DIR.glob("[0-9][0-9][0-9]_*.sql")):
        db.executescript(path.read_text(encoding="utf-8"))


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="summit_backup_catalog_") as td:
        db = sqlite3.connect(Path(td) / "summit.sqlite3")
        apply_all(db)

        physical = {
            row[0]
            for row in db.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"
            )
        }
        missing = sorted(set(EXPECTED_BACKUP_TABLES) - physical)
        assert not missing, f"backup-proven tables missing from SQLite: {missing!r}"

        for table, expected in EXPECTED_NEW.items():
            info = db.execute(f'PRAGMA table_info("{table}")').fetchall()
            actual_names = [row[1] for row in info]
            expected_names = [row[0] for row in expected]
            assert actual_names == expected_names, (
                f"{table}: column order {actual_names!r} != {expected_names!r}"
            )

            for row, (_, affinity, identity, nullable) in zip(info, expected):
                actual_type = (row[2] or "").upper()
                expected_type = "INTEGER" if identity else affinity
                assert actual_type == expected_type, (
                    f"{table}.{row[1]}: type {actual_type!r} != {expected_type!r}"
                )
                if identity:
                    assert row[5] == 1, f"{table}.{row[1]}: IDENTITY translation is not INTEGER PRIMARY KEY"
                else:
                    expected_notnull = 0 if nullable else 1
                    assert row[3] == expected_notnull, (
                        f"{table}.{row[1]}: notnull={row[3]} expected {expected_notnull}"
                    )

        user_tables = len(physical)
        assert user_tables == 332, user_tables
        db.close()

    print(
        "Backup catalog completion PASS: "
        f"new_tables={len(EXPECTED_NEW)}, "
        f"backup_tables_present={len(EXPECTED_BACKUP_TABLES)}, "
        "exact new column order/affinity/nullability/identity=PASS, "
        "user_tables=332"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
